"""Generate the UXUY trade catalog from its checked-in bilingual source."""
import argparse
import csv
import json
import re
import subprocess
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    package = Path(__file__).resolve().parents[1] / "packages/uxuy_trade"
    target = package / "lib/src/strings.g.dart"
    with (package / "translations/l10n.tsv").open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source, delimiter="\t"))
    keys = [row["key"] for row in rows]
    if not rows or len(set(keys)) != len(keys) or not all(re.fullmatch(r"\w+", k, re.ASCII) for k in keys):
        raise ValueError("Empty catalog, duplicate key, or invalid key")
    lines = [
        "// GENERATED by tool/generate_strings.py; edit translations/l10n.tsv.",
        "import 'package:flutter/widgets.dart';",
        "String demoText(BuildContext context, String key) {",
        "final language = Localizations.localeOf(context).languageCode;",
        "return (_catalog[language] ?? _catalog['en']!)[key]!;",
        "}",
        "const Map<String, Map<String, String>> _catalog = {",
    ]
    for locale, column in [("en", "en"), ("zh", "zh_Hans")]:
        lines.append(f"'{locale}': {{")
        for row in rows:
            if not row[column]:
                raise ValueError(f"Missing {column} translation for {row['key']}")
            value = json.dumps(row[column], ensure_ascii=False).replace("$", r"\$")
            lines.append(f"'{row['key']}': {value},")
        lines.append("},")
    lines.append("};")
    formatter = ["dart", "format", "--output=show", "--summary=none"]
    output = subprocess.check_output(
        [*formatter, "--stdin-name", str(target)], input="\n".join(lines).encode("utf-8"),
    )
    if target.is_file() and subprocess.check_output([*formatter, str(target)]) == output:
        return
    if args.check:
        parser.exit(1, "Translation catalog is out of date.\n")
    target.write_bytes(output)


if __name__ == "__main__":
    main()
